<?php

namespace App\Services\Accounting;

use App\Exceptions\AccountingException;
use App\Models\Account;
use App\Models\FiscalPeriod;
use App\Models\JournalEntry;
use App\Models\JournalLine;
use App\Models\User;
use App\Models\AuditLog;
use App\Support\Money;
use App\Support\Perm;
use Illuminate\Support\Facades\DB;

/**
 * The only way an entry becomes "posted" or "reversed". Every rule from
 * requirements §6 is enforced here, independent of any screen.
 */
class PostingService
{
    public function __construct(private SequenceService $sequences) {}

    /** Create a draft entry with lines. $lines: [['account_id','debit','credit','description', ...], ...] */
    public function createDraft(array $header, array $lines, User $user): JournalEntry
    {
        $this->authorize($user, Perm::ENTRIES_DRAFT);

        return DB::transaction(function () use ($header, $lines, $user) {
            $entry = JournalEntry::create($header + ['created_by' => $user->id, 'status' => 'draft']);
            $this->replaceLines($entry, $lines);
            AuditLog::record('created', $entry, null, $this->snapshot($entry));

            return $entry;
        });
    }

    public function updateDraft(JournalEntry $entry, array $header, array $lines, User $user): JournalEntry
    {
        $this->authorize($user, Perm::ENTRIES_DRAFT);
        $this->assertManualDraft($entry);

        return DB::transaction(function () use ($entry, $header, $lines) {
            $before = $this->snapshot($entry);
            $entry->update($header);
            $this->replaceLines($entry, $lines);
            AuditLog::record('updated', $entry, $before, $this->snapshot($entry->fresh()));

            return $entry;
        });
    }

    public function deleteDraft(JournalEntry $entry, User $user): void
    {
        $this->authorize($user, Perm::ENTRIES_DRAFT);
        $this->assertManualDraft($entry);
        DB::transaction(function () use ($entry) {
            AuditLog::record('deleted', $entry, $this->snapshot($entry), null);
            $entry->lines()->delete();
            $entry->delete();
        });
    }

    public function replaceLines(JournalEntry $entry, array $lines): void
    {
        $entry->lines()->delete();
        $total = 0;
        foreach (array_values($lines) as $i => $l) {
            $dr = Money::toCents($l['debit'] ?? 0);
            $cr = Money::toCents($l['credit'] ?? 0);
            $total += $dr;
            JournalLine::create([
                'journal_entry_id' => $entry->id,
                'account_id' => $l['account_id'],
                'party_id' => $l['party_id'] ?? null,
                'debit' => Money::fromCents($dr),
                'credit' => Money::fromCents($cr),
                'description' => $l['description'] ?? null,
                'tax_code_id' => $l['tax_code_id'] ?? null,
                'is_tax_line' => (bool) ($l['is_tax_line'] ?? false),
                'tax_direction' => ! empty($l['tax_code_id']) ? ($l['tax_direction'] ?? ($cr > 0 ? 'sale' : 'purchase')) : null,
                'tax_base' => isset($l['tax_base']) ? Money::fromCents(Money::toCents($l['tax_base'])) : null,
                'sort' => $i,
            ]);
        }
        $entry->forceFill(['total' => Money::fromCents($total)])->saveQuietly();
    }

    /**
     * Post a draft. $system = true only for entries generated by documents (vouchers, year close),
     * which are authorised through the document's own permission.
     */
    public function post(JournalEntry $entry, User $user, bool $system = false): JournalEntry
    {
        if (! $system) {
            $this->authorize($user, Perm::ENTRIES_POST);
            if ($entry->isAutomatic()) {
                throw new AccountingException(__('This entry was generated by a document. Post the document instead.'));
            }
        }

        return DB::transaction(function () use ($entry, $user, $system) {
            /** @var JournalEntry $entry */
            $entry = JournalEntry::whereKey($entry->id)->lockForUpdate()->firstOrFail();
            if ($entry->status !== 'draft') {
                throw new AccountingException(__('Only draft entries can be posted.'));
            }
            if (! $system && $entry->company->segregation_of_duties && $entry->created_by === $user->id) {
                throw new AccountingException(__('Segregation of duties: the person who entered a document cannot post it.'));
            }
            if (! $user->canUseBranch($entry->branch)) {
                throw new AccountingException(__('You are not allowed to work on this branch.'));
            }

            $period = $this->validate($entry);

            $type = match ($entry->type) {
                'voucher', 'invoice' => null, // numbered by the source document
                'reversal' => 'REV',
                'opening' => 'OPN',
                'closing' => 'CLS',
                default => 'JV',
            };
            $number = $type ? $this->sequences->next($entry->company_id, $type, (int) $entry->date->format('Y')) : $entry->number;

            $entry->forceFill([
                'status' => 'posted',
                'number' => $number,
                'fiscal_period_id' => $period->id,
                'posted_by' => $user->id,
                'posted_at' => now(),
            ]);
            // forceFill on a draft passes the model guard because original status is draft.
            $entry->save();
            AuditLog::record('posted', $entry, ['status' => 'draft'], $this->snapshot($entry));

            return $entry;
        });
    }

    /** Validate an entry against all posting rules; returns its open period. */
    public function validate(JournalEntry $entry): FiscalPeriod
    {
        $lines = $entry->lines()->with('account')->get();
        if ($lines->count() < 2) {
            throw new AccountingException(__('An entry needs at least two lines.'));
        }

        $dr = 0;
        $cr = 0;
        foreach ($lines as $l) {
            $d = Money::toCents($l->debit);
            $c = Money::toCents($l->credit);
            if ($d < 0 || $c < 0 || ($d > 0 && $c > 0) || ($d === 0 && $c === 0)) {
                throw new AccountingException(__('Each line must have either a debit or a credit amount, not both.'));
            }
            $a = $l->account;
            if (! $a || $a->company_id !== $entry->company_id) {
                throw new AccountingException(__('Account does not belong to this company.'));
            }
            if (! $a->is_postable) {
                throw new AccountingException(__('Account :code is a parent account and cannot take postings.', ['code' => $a->code]));
            }
            if (! $a->is_active) {
                throw new AccountingException(__('Account :code is inactive.', ['code' => $a->code]));
            }
            $dr += $d;
            $cr += $c;
        }
        if ($dr !== $cr) {
            throw new AccountingException(__('Entry is not balanced: debit :d, credit :c.', ['d' => Money::format($dr), 'c' => Money::format($cr)]));
        }

        $period = $this->periodFor($entry->company_id, $entry->date->toDateString());

        if (! $entry->company->allow_negative_cash) {
            $this->assertCashNotNegative($entry, $lines);
        }

        return $period;
    }

    public function periodFor(int $companyId, string $date): FiscalPeriod
    {
        $period = FiscalPeriod::where('company_id', $companyId)
            ->whereDate('start_date', '<=', $date)->whereDate('end_date', '>=', $date)->first();
        if (! $period) {
            throw new AccountingException(__('No fiscal period exists for :date.', ['date' => $date]));
        }
        if (! $period->isOpen()) {
            throw new AccountingException(__('The period :p is closed. Posting is not allowed.', ['p' => $period->label]));
        }
        if ($period->fiscalYear->isClosed()) {
            throw new AccountingException(__('The fiscal year is closed.'));
        }

        return $period;
    }

    private function assertCashNotNegative(JournalEntry $entry, $lines): void
    {
        $movement = [];
        foreach ($lines as $l) {
            if ($l->account->is_cash) {
                $movement[$l->account_id] = ($movement[$l->account_id] ?? 0) + Money::toCents($l->debit) - Money::toCents($l->credit);
            }
        }
        foreach ($movement as $accountId => $delta) {
            if ($delta >= 0) {
                continue;
            }
            $row = DB::table('journal_lines')->join('journal_entries', 'journal_entries.id', '=', 'journal_lines.journal_entry_id')
                ->where('journal_lines.account_id', $accountId)->whereIn('journal_entries.status', ['posted', 'reversed'])
                ->whereDate('journal_entries.date', '<=', $entry->date)
                ->selectRaw('COALESCE(SUM(debit),0) d, COALESCE(SUM(credit),0) c')->first();
            $balance = Money::toCents((string) $row->d) - Money::toCents((string) $row->c);
            if ($balance + $delta < 0) {
                $acc = Account::find($accountId);
                throw new AccountingException(__('Cash box :code would go negative (balance :b).', ['code' => $acc->code, 'b' => Money::format($balance)]));
            }
        }
    }

    /**
     * Reverse a posted entry with a linked mirror entry (§6.2). Both stay visible.
     * The reversal is dated $date (default: original date) and must fall in an open period.
     */
    public function reverse(JournalEntry $entry, User $user, ?string $reason = null, ?string $date = null, bool $system = false): JournalEntry
    {
        if (! $system) {
            $this->authorize($user, Perm::ENTRIES_REVERSE);
            if ($entry->isAutomatic()) {
                throw new AccountingException(__('This entry was generated by a document. Cancel the document instead.'));
            }
        }

        return DB::transaction(function () use ($entry, $user, $reason, $date) {
            $entry = JournalEntry::whereKey($entry->id)->lockForUpdate()->firstOrFail();
            if ($entry->status !== 'posted' || $entry->reverses_id) {
                throw new AccountingException(__('Only a posted, not-yet-reversed entry can be reversed.'));
            }

            $rev = JournalEntry::create([
                'company_id' => $entry->company_id,
                'branch_id' => $entry->branch_id,
                'type' => 'reversal',
                'date' => $date ?? $entry->date->toDateString(),
                'description' => __('Reversal of :n', ['n' => $entry->number]).($reason ? ' — '.$reason : ''),
                'reference' => $entry->number,
                'reverses_id' => $entry->id,
                'source_type' => $entry->source_type,
                'source_id' => $entry->source_id,
                'created_by' => $user->id,
            ]);
            $this->replaceLines($rev, $entry->lines->map(fn ($l) => [
                'account_id' => $l->account_id,
                'party_id' => $l->party_id,
                'debit' => $l->credit,
                'credit' => $l->debit,
                'description' => $l->description,
                'tax_code_id' => $l->tax_code_id,
                'is_tax_line' => $l->is_tax_line,
                'tax_direction' => $l->tax_direction,
                'tax_base' => $l->tax_base !== null ? Money::fromCents(-Money::toCents($l->tax_base)) : null,
            ])->all());

            $rev = $this->post($rev, $user, system: true);

            $entry->forceFill(['status' => 'reversed', 'reversed_by_id' => $rev->id])->save();
            AuditLog::record('reversed', $entry, ['status' => 'posted'], ['status' => 'reversed', 'reversal' => $rev->number], $reason);

            return $rev;
        });
    }

    public function authorize(User $user, string $permission): void
    {
        if (! $user->can($permission)) {
            throw new AccountingException(__('You do not have permission: :p', ['p' => Perm::LABELS[$permission] ?? $permission]));
        }
    }

    private function assertManualDraft(JournalEntry $entry): void
    {
        if (! $entry->isDraft()) {
            throw new AccountingException(__('Only draft entries can be changed.'));
        }
        if ($entry->isAutomatic()) {
            throw new AccountingException(__('This entry was generated by a document and cannot be edited by hand.'));
        }
    }

    public function snapshot(JournalEntry $e): array
    {
        return $e->only(['number', 'date', 'branch_id', 'description', 'status', 'total']) + [
            'date' => $e->date?->toDateString(),
            'lines' => $e->lines()->get(['account_id', 'debit', 'credit', 'description'])->toArray(),
        ];
    }
}
